const searchForm = document.querySelector("#filters-form");
const searchInput = document.querySelector("#service-search");
const departmentFilter = document.querySelector("#department-filter");
const pageSizeSelect = document.querySelector("#page-size");
const resultsCount = document.querySelector("#results-count");
const serviceGrid = document.querySelector("#service-grid");
const pagination = document.querySelector("#pagination");
let currentPage = 1;

function getNameInitials(name) {
  const words = (name.normalize("NFD").replace(/[\u0300-\u036f]/g, "").match(/[A-Za-z0-9]+/g) || [])
    .filter(word => !["DE", "DEL", "LA", "LAS", "EL", "LOS", "Y", "SA", "SAS", "ESP"].includes(word.toUpperCase()));
  return words.slice(0, 2).map(word => word[0]).join("").toUpperCase() || "?";
}

function normalizeText(value) {
  return value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

function getFilteredServices() {
  const searchTerm = normalizeText(searchInput.value.trim());
  return services.filter(service => normalizeText(service.name).includes(searchTerm));
}

function renderCards(items) {
  serviceGrid.replaceChildren();

  if (items.length === 0) {
    const emptyMessage = document.createElement("p");
    emptyMessage.className = "empty-results";
    emptyMessage.textContent = "No se encontraron convenios.";
    serviceGrid.append(emptyMessage);
    return;
  }

  items.forEach(service => {
    const card = document.createElement("article");
    card.className = "service-card";

    const logoSlot = document.createElement("div");
    logoSlot.className = "provider-logo";

    const logo = document.createElement("img");
    logo.src = service.logo;
    logo.alt = "";

    const payLink = document.createElement("a");
    payLink.className = "pay-link";
    payLink.href = "medios-pago.html?" + new URLSearchParams({ servicio: service.name, logo: service.logo });
    payLink.textContent = "Pagar";
    payLink.setAttribute("aria-label", "Pagar " + service.name);
    logo.addEventListener("error", () => {
      logo.remove();
      const fallback = document.createElement("span");
      fallback.className = "provider-logo-fallback";
      fallback.setAttribute("aria-hidden", "true");
      fallback.textContent = getNameInitials(service.name);
      logoSlot.insertBefore(fallback, payLink);
    }, { once: true });

    const name = document.createElement("p");
    name.className = "service-name";
    name.textContent = service.name;

    logoSlot.append(logo, payLink);
    card.append(logoSlot, name);
    serviceGrid.append(card);
  });
}

function renderPagination(pageCount) {
  pagination.replaceChildren();
  const visiblePages = Array.from({ length: pageCount }, (_, index) => index + 1);

  function addButton(label, page, ariaLabel, disabled = false) {
    const button = document.createElement("button");
    button.type = "button";
    button.className = page === null ? "page-button arrow" : "page-button";
    button.textContent = label;
    button.setAttribute("aria-label", ariaLabel);
    button.disabled = disabled;
    if (page === currentPage) button.setAttribute("aria-current", "page");
    button.addEventListener("click", () => {
      currentPage = page === null ? currentPage + (label === "\u2039" ? -1 : 1) : page;
      render();
    });
    pagination.append(button);
  }

  addButton("\u2039", null, "P\u00e1gina anterior", currentPage === 1);
  visiblePages.forEach(page => {
    if (page === "\u2026") {
      const ellipsis = document.createElement("span");
      ellipsis.className = "page-ellipsis";
      ellipsis.textContent = "\u2026";
      pagination.append(ellipsis);
    } else {
      addButton(String(page), page, "P\u00e1gina " + page);
    }
  });

  addButton("\u203a", null, "P\u00e1gina siguiente", currentPage === pageCount);
}

function render() {
  const filteredServices = getFilteredServices();
  const pageSize = Number(pageSizeSelect.value);
  const pageCount = Math.max(1, Math.ceil(filteredServices.length / pageSize));
  currentPage = Math.min(currentPage, pageCount);

  const startIndex = (currentPage - 1) * pageSize;
  const visibleServices = filteredServices.slice(startIndex, startIndex + pageSize);
  const shownCount = Math.min(startIndex + visibleServices.length, filteredServices.length);
  resultsCount.textContent = shownCount + " de " + filteredServices.length + " resultados";

  renderCards(visibleServices);
  renderPagination(pageCount);
}

searchForm.addEventListener("submit", event => {
  event.preventDefault();
  currentPage = 1;
  render();
});

pageSizeSelect.addEventListener("change", () => {
  currentPage = 1;
  render();
});

departmentFilter.addEventListener("change", () => {
  currentPage = 1;
  render();
});

render();

